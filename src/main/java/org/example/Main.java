package org.example;

// Нажмите Shift дважды, чтобы открыть диалог "Поиск везде" и введите `show whitespaces`,
// затем нажмите Enter. Теперь вы можете видеть символы пробелов в вашем коде.
public class Main {
    public static void main(String[] args) {
        // Нажмите Alt+Enter, когда курсор находится на подсвеченном тексте,
        // чтобы увидеть предложения IntelliJ IDEA по исправлению.
        System.out.printf("Hello and welcome!");

        // Нажмите Shift+F10 или зеленую стрелку на полях, чтобы запустить код.
        for (int i = 1; i <= 5; i++) {

            // Нажмите Shift+F9, чтобы начать отладку кода. Мы установили одну точку останова
            // для вас, но вы всегда можете добавить больше, нажав Ctrl+F8.
            System.out.println("i = " + i);
        }
    }
}